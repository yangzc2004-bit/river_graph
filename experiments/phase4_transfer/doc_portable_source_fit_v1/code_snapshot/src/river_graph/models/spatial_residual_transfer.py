"""Station-blocked residual transfer for spatial DOC extrapolation.

This module is intentionally smaller than the graph residual models.  A
Temporal RF-context prediction is the fixed base.  A second forest learns the
OOF base error on source stations from features that are available at a target
station without reading its DOC labels (hydro, ecology, static coordinates,
and calendar).  The residual is then transferred to held-out stations by
feature similarity.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from sklearn.ensemble import RandomForestRegressor

from river_graph.experiments.temporal_h2x import TARGET_TRANSFORMS, _as_tensor
from river_graph.models.kgml_local_transport import (
    TEST_ROLES,
    RFArtifacts,
    fit_rf_artifacts,
    target_values,
)

SIMILARITY_FEATURE_NAMES = (
    "temperature", "discharge", "temperature_visible", "discharge_visible",
    "month_sin", "month_cos", "latitude", "longitude",
    *(f"regime_{i}" for i in range(13)),
)


def build_similarity_features(dataset: dict) -> np.ndarray:
    """Build label-free station/month features for residual transfer.

    No target values, target masks, graph edges, or station identifiers enter
    this matrix.  This makes the transfer branch a genuine source-station
    similarity model rather than a disguised target-station interpolation.
    """
    x = _as_tensor(dataset["x"]).numpy().astype(np.float32)
    x_mask = _as_tensor(dataset["x_mask"]).numpy().astype(np.float32)
    n, t, _ = x.shape
    phase = 2 * np.pi * (
        np.asarray(dataset["months"], dtype="datetime64[M]").astype(int) % 12
    ) / 12
    calendar = np.broadcast_to(
        np.stack([np.sin(phase), np.cos(phase)], axis=-1), (n, t, 2)
    ).astype(np.float32)
    blocks = [x, x_mask, calendar]
    for key in ("static", "regime"):
        value = _as_tensor(dataset[key]).numpy().astype(np.float32)
        blocks.append(np.broadcast_to(value[:, None, :], (n, t, value.shape[1])))
    features = np.concatenate(blocks, axis=-1).reshape(n * t, -1)
    if features.shape[1] != len(SIMILARITY_FEATURE_NAMES):
        raise ValueError("similarity feature schema mismatch")
    if not np.isfinite(features).all():
        raise ValueError("similarity features contain nonfinite values")
    return features


def _source_cells(split: dict, n: int, t: int) -> np.ndarray:
    cells = np.asarray(split.get("train", []), dtype=np.int64)
    if not len(cells):
        raise ValueError("source-station residual transfer requires train cells")
    if cells.min() < 0 or cells.max() >= n * t:
        raise ValueError("source cells outside target grid")
    return cells


@dataclass
class SpatialResidualTransfer:
    """Fixed RF-context plus source-station OOF residual transfer."""

    seed: int = 42
    n_estimators: int = 200
    n_jobs: int = 4
    max_features: float | str = 1.0

    def fit(self, dataset: dict, split: dict, rf: RFArtifacts | None = None) -> None:
        n, t = dataset["y"].shape
        source = _source_cells(split, n, t)
        if rf is None:
            rf = fit_rf_artifacts(
                dataset, split, target_transform=TARGET_TRANSFORMS["doc"],
                seed=self.seed, n_estimators=self.n_estimators, n_jobs=self.n_jobs,
            )
        if rf.context_oof_z is None:
            raise ValueError("context OOF predictions are required")
        # The OOF base was generated by station-blocked folds.  Only source
        # train cells are allowed to supervise the transfer forest.
        oof = np.asarray(rf.context_oof_z).reshape(-1)
        y_z = target_values(dataset, rf.target_transform).reshape(-1)
        residual = (y_z - oof) / max(float(rf.target_sd), 1e-8)
        features = build_similarity_features(dataset)
        if not np.isfinite(residual[source]).all():
            raise ValueError("source OOF residual coverage is incomplete")
        self.rf = rf
        self.dataset = dataset
        self.split = split
        self.features = features
        self.source_cells = source.copy()
        self.source_stations = np.unique(source // t)
        self.residual_forest = RandomForestRegressor(
            n_estimators=self.n_estimators,
            n_jobs=self.n_jobs,
            random_state=self.seed,
            max_features=self.max_features,
        )
        self.residual_forest.fit(features[source], residual[source])
        self.target_transform = rf.target_transform
        self.residual_train_std = residual[source]

    def predict_components(self, visible_roles=TEST_ROLES) -> dict[str, np.ndarray]:
        if not hasattr(self, "rf"):
            raise RuntimeError("fit must be called before predict")
        local_std, context_std = self.rf.predict_std(
            self.dataset, self.split, visible_roles
        )
        delta_std = self.residual_forest.predict(self.features).reshape(context_std.shape)
        base = self.rf.inverse_std(context_std)
        final = self.rf.inverse_std(context_std + delta_std)
        if not np.isfinite(final).all():
            raise FloatingPointError("nonfinite spatial residual transfer prediction")
        # DOC and EC residuals are in log1p units; pH would be standardized.
        raw_delta = delta_std * self.rf.target_sd
        if self.target_transform == "standard":
            raw_delta = delta_std * self.rf.target_sd
        return {
            "local_pred": self.rf.inverse_std(local_std),
            "context_pred": base.copy(),
            "base_pred": base,
            "final_pred": final,
            "graph_delta": raw_delta,
            "graph_delta_std": delta_std,
            "graph_delta_raw": final - base,
            "graph_delta_abs": np.abs(raw_delta),
        }

    def predict(self, visible_roles=TEST_ROLES) -> np.ndarray:
        return self.predict_components(visible_roles)["final_pred"]


__all__ = ["SIMILARITY_FEATURE_NAMES", "SpatialResidualTransfer", "build_similarity_features"]
